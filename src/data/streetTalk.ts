function poolOf(id: string, game: "osrs" | "rs3"): string[] {
  const raw = game === "osrs" ? OSRS[id] : RS3[id];
  const out = [...(raw ?? [])];
  while (out.length < 6) out.push(QUIET);
  return out.slice(0, Math.max(6, out.length));
}

export function streetTalk(id: string, game: "osrs" | "rs3"): string[] {
  return poolOf(id, game);
}

export function streetLine(id: string, game: "osrs" | "rs3", now = Date.now()): string {
  const pool = streetTalk(id, game);
  const slot = Math.floor(now / STREET_SLOT_MS);
  return pool[slot % pool.length] ?? QUIET;
}
